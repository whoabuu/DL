import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers
import matplotlib.pyplot as plt
import numpy as np
import os

img_size = (150, 150)
batch_size = 32

train_ds = keras.utils.image_dataset_from_directory(
    '/Users/abubakartamboli/Downloads/Pneumonia X Ray/chest_xray/train',
    image_size=img_size,
    batch_size=batch_size,
    color_mode="grayscale",
    label_mode="binary"
)

val_ds = keras.utils.image_dataset_from_directory(
    '/Users/abubakartamboli/Downloads/Pneumonia X Ray/chest_xray/val',
    image_size=img_size,
    batch_size=batch_size,
    color_mode="grayscale",
    label_mode="binary"
)

test_ds = keras.utils.image_dataset_from_directory(
    '/Users/abubakartamboli/Downloads/Pneumonia X Ray/chest_xray/test',
    image_size=img_size,
    batch_size=batch_size,
    color_mode="grayscale",
    label_mode="binary"
)

print("Classes:", train_ds.class_names)

images, labels = next(iter(train_ds))
plt.figure(figsize=(10, 8))

for i in range(8):
    plt.subplot(2, 4, i + 1)

    # Display image
    plt.imshow(images[i].numpy().squeeze(), cmap='gray')

    # Display class name
    label = int(labels[i].numpy()[0])
    plt.title(train_ds.class_names[label])

    plt.axis('off')

plt.show()

class_names = train_ds.class_names

print(class_names)

# Normalize pixel values
normalization = layers.Rescaling(1./255)

train_ds = train_ds.map(
    lambda x, y: (normalization(x), y)
)

val_ds = val_ds.map(
    lambda x, y: (normalization(x), y)
)

test_ds = test_ds.map(
    lambda x, y: (normalization(x), y)
)

# Create CNN model
model = keras.Sequential([

    # First convolution layer
    layers.Conv2D(
        32, (3, 3),
        activation='relu',
        input_shape=(150, 150, 1)
    ),

    # First pooling layer
    layers.MaxPooling2D((2, 2)),

    # Second convolution layer
    layers.Conv2D(64, (3, 3), activation='relu'),

    # Second pooling layer
    layers.MaxPooling2D((2, 2)),

    # Third convolution layer
    layers.Conv2D(128, (3, 3), activation='relu'),

    # Third pooling layer
    layers.MaxPooling2D((2, 2)),

    # Flatten feature maps
    layers.Flatten(),

    # Fully connected layer
    layers.Dense(128, activation='relu'),

    # Output layer
    layers.Dense(1, activation='sigmoid')
])

model.compile(
    optimizer='adam',
    loss='binary_crossentropy',
    metrics=['accuracy']
)

# Display model architecture
model.summary()

history = model.fit(
    train_ds,
    epochs=5,
    validation_data=val_ds
)

loss, accuracy = model.evaluate(test_ds)

print("Test Loss:", loss)
print("Test Accuracy:", accuracy)

images, labels = next(iter(test_ds))
# Select an image
index = 0

# Predict image
prediction = model.predict(
    images[index:index+1],
    verbose=0
)

# Convert prediction to class
predicted_class = 1 if prediction[0][0] >= 0.5 else 0

# Get actual class
actual_class = int(labels[index].numpy()[0])

# Display image
plt.imshow(images[index].numpy().squeeze(), cmap='gray')

plt.title(
    "Predicted: " + class_names[predicted_class] +
    "\nActual: " + class_names[actual_class]
)

plt.axis('off')
plt.show()

print("Predicted Class:",class_names[predicted_class])
print("Actual Class:", class_names[actual_class])


import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers

from sklearn.model_selection import train_test_split

data = pd.read_csv("mnist_784_csv.csv")

print("Dataset Shape:", data.shape)
print(data.head())

# Separate labels and pixel values
if data.shape[1] == 785:

    # First column contains digit labels
    labels = data.iloc[:, 0].values

    # Remaining columns contain pixel values
    X = data.iloc[:, 1:].values

else:

    # Dataset contains only pixel values
    X = data.values
    labels = None

# Convert to float
X = X.astype("float32")

# Normalize pixel values
X = X / 255.0

print("Images Shape:", X.shape)

# Display 10 sample images
plt.figure(figsize=(10, 4))

for i in range(10):

    # Convert 784 pixels into 28 x 28 image
    image = X[i].reshape(28, 28)

    plt.subplot(2, 5, i + 1)

    plt.imshow(image, cmap="gray")

    if labels is not None:
        plt.title("Digit: " + str(labels[i]))
    else:
        plt.title("Image " + str(i + 1))

    plt.axis("off")

plt.tight_layout()
plt.show()

# Split dataset
x_train, x_test = train_test_split(
    X,
    test_size=0.2,
    random_state=42
)

print("Training Data:", x_train.shape)
print("Testing Data:", x_test.shape)

# Input layer
input_img = keras.Input(shape=(784,))

# Encoder
encoded = layers.Dense(
    128,
    activation="relu"
)(input_img)

# Sparse encoded representation
encoded = layers.Dense(
    32,
    activation="relu",
    activity_regularizer=keras.regularizers.l1(0.001)
)(encoded)

# Decoder
decoded = layers.Dense(
    128,
    activation="relu"
)(encoded)

# Reconstructed image
output_img = layers.Dense(
    784,
    activation="sigmoid"
)(decoded)

# Create autoencoder
autoencoder = keras.Model(
    input_img,
    output_img
)

# Display model summary
autoencoder.summary()

# Compile model
autoencoder.compile(
    optimizer="adam",
    loss="binary_crossentropy"
)

# Train model
history = autoencoder.fit(
    x_train,
    x_train,
    epochs=10,
    batch_size=256,
    shuffle=True,
    validation_split=0.1
)

# Evaluate model
loss = autoencoder.evaluate(
    x_test,
    x_test,
    verbose=0
)

print("Test Reconstruction Loss:", loss)

# Reconstruct first 10 test images
reconstructed = autoencoder.predict(
    x_test[:10],
    verbose=0
)

# Display original and reconstructed images
plt.figure(figsize=(12, 5))

for i in range(10):

    # Original image
    plt.subplot(2, 10, i + 1)

    plt.imshow(
        x_test[i].reshape(28, 28),
        cmap="gray"
    )

    plt.title("Original")
    plt.axis("off")

    # Reconstructed image
    plt.subplot(2, 10, i + 11)

    plt.imshow(
        reconstructed[i].reshape(28, 28),
        cmap="gray"
    )

    plt.title("Reconstructed")
    plt.axis("off")

plt.tight_layout()
plt.show()

# Create encoder model
encoder = keras.Model(
    autoencoder.input,
    autoencoder.layers[2].output
)

# Get encoded representations
encoded_images = encoder.predict(
    x_test[:10],
    verbose=0
)

# Display encoded representation
print("Encoded Representation:")
print(encoded_images[0])

# Calculate sparsity
sparsity = np.mean(
    np.abs(encoded_images) < 0.01
)

print("Sparsity Percentage:", sparsity * 100)


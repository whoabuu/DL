import numpy as np

np.random.seed(42)

X = np.array([[1, 0], [0, 1], [1, 1]])

Wx = np.random.rand(2, 3)
Wh = np.random.rand(3, 3)
Wy = np.random.rand(3, 1)

h = np.zeros((1, 3))

print("Input X:\n", X)
print("Input Weights Wx:\n", Wx)
print("Hidden Weights Wh:\n", Wh)
print("Output Weights Wy:\n", Wy)
print("Initial Hidden State h:\n", h)

def sigmoid(x):
    return 1 / (1 + np.exp(-x))

for t in range(len(X)):

    x = X[t].reshape(1, 2)

    h = np.tanh(np.dot(x, Wx) + np.dot(h, Wh))

    y = sigmoid(np.dot(h, Wy))

    print("\nTime Step:", t+1)
    print("Input:", x)
    print("Hidden State:", h)
    print("Output:", y)

print("Final Hidden State:", h)
print("Final RNN Output:", y)


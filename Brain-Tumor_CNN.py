import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import *
from tensorflow.keras import layers, models

train_dir = r"path"

test_dir = r"path"

IMG_SIZE = (128, 128)
BATCH_SIZE = 32
SEED = 123

train_ds = tf.keras.utils.image_dataset_from_directory(
    train_dir,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    label_mode="int",
    color_mode="grayscale",
    validation_split=0.2,
    subset="training",
    seed=SEED
)

val_ds = tf.keras.utils.image_dataset_from_directory(
    train_dir,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    label_mode="int",
    color_mode="grayscale",
    validation_split=0.2,
    subset="validation",
    seed=SEED
)

class_names = train_ds.class_names
num_classes = len(class_names)

# Keep the test labels in exactly the same class order as the training labels.
test_ds = tf.keras.utils.image_dataset_from_directory(
    test_dir,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    label_mode="int",
    color_mode="grayscale",
    class_names=class_names,
    shuffle=False
)

print("Class Names:", class_names)
print("Number of Classes:", num_classes)
print("Training batches:", len(train_ds))
print("Validation batches:", len(val_ds))
print("Testing batches:", len(test_ds))

for images, labels in train_ds.take(1):
    plt.imshow(images[0].numpy().squeeze(), cmap="gray")
    plt.title(class_names[int(labels[0].numpy())])
    plt.axis("off")
    plt.show()

# Check the shape of one batch.
for images, labels in train_ds.take(1):
    print("Image batch shape:", images.shape)
    print("Label batch shape:", labels.shape)

model = models.Sequential([
    layers.Input(shape=(128, 128, 1)),

    layers.Rescaling(1.0 / 255),

    layers.Conv2D(32, (3, 3), activation="relu"),
    layers.MaxPooling2D(2, 2),

    layers.Conv2D(64, (3, 3), activation="relu"),
    layers.MaxPooling2D(2, 2),

    layers.Flatten(),
    layers.Dense(128, activation="relu"),
    layers.Dense(num_classes, activation="softmax")
])

model.compile(
    optimizer="adam",
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

model.summary()

history = model.fit(
    train_ds,
    epochs=5,
    validation_data=val_ds
)

loss, accuracy = model.evaluate(test_ds)

print("Test Loss:", loss)
print("Test Accuracy:", accuracy * 100, "%")

plt.figure(figsize=(8, 5))

plt.plot(history.history["accuracy"], label="Training Accuracy")
plt.plot(history.history["val_accuracy"], label="Validation Accuracy")

plt.xlabel("Epochs")
plt.ylabel("Accuracy")
plt.title("Brain Tumor Model Accuracy")
plt.legend()
plt.grid(True)
plt.show()

# Predict one randomly selected image from the test dataset.
for images, labels in test_ds.take(1):
    n = np.random.randint(0, len(images))

    prediction = model.predict(images[n:n + 1], verbose=0)
    predicted_class = int(np.argmax(prediction[0]))
    actual_class = int(labels[n].numpy())

    print("PREDICTION")
    print("----------------------")
    print("Predicted Class:", predicted_class)
    print("Predicted Name:", class_names[predicted_class])
    print("Actual Class:", actual_class)
    print("Actual Name:", class_names[actual_class])
    print("Confidence:", float(prediction[0][predicted_class]) * 100, "%")

    plt.imshow(images[n].numpy().squeeze(), cmap="gray")
    plt.title(
        "Predicted: " + class_names[predicted_class] +
        "\nActual: " + class_names[actual_class]
    )
    plt.axis("off")
    plt.show()

# Display predictions for up to five test images.
for images, labels in test_ds.take(1):
    predictions = model.predict(images, verbose=0)

    count = min(5, len(images))
    plt.figure(figsize=(12, 6))

    for i in range(count):
        predicted_class = int(np.argmax(predictions[i]))
        actual_class = int(labels[i].numpy())

        plt.subplot(1, count, i + 1)
        plt.imshow(images[i].numpy().squeeze(), cmap="gray")
        plt.title(
            f"Actual: {class_names[actual_class]}\n"
            f"Predicted: {class_names[predicted_class]}"
        )
        plt.axis("off")

    plt.tight_layout()
    plt.show()


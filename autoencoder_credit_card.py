import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

data = pd.read_csv("Credit Card Customer Data.csv")

print("Dataset Shape:", data.shape)

print(data.head())

print(data.isnull().sum())

# Select useful features
features = [
    'Avg_Credit_Limit',
    'Total_Credit_Cards',
    'Total_visits_bank',
    'Total_visits_online',
    'Total_calls_made'
]

# Extract feature data
X = data[features]

# Handle missing values
X = X.fillna(X.median())

print("Features Shape:", X.shape)

# Split dataset
x_train, x_test = train_test_split(
    X,
    test_size=0.2,
    random_state=42
)

# Normalize data
scaler = StandardScaler()

x_train = scaler.fit_transform(x_train)
x_test = scaler.transform(x_test)

print("Training Data:", x_train.shape)
print("Testing Data:", x_test.shape)

# Input layer
input_layer = keras.Input(shape=(5,))

# Encoder
encoded = layers.Dense(
    4,
    activation='relu'
)(input_layer)

# Bottleneck layer
encoded = layers.Dense(
    2,
    activation='relu'
)(encoded)

# Decoder
decoded = layers.Dense(
    4,
    activation='relu'
)(encoded)

# Reconstructed output
output_layer = layers.Dense(
    5,
    activation='linear'
)(decoded)

# Create autoencoder
autoencoder = keras.Model(
    input_layer,
    output_layer
)

# Display model
autoencoder.summary()

# Compile autoencoder
autoencoder.compile(
    optimizer='adam',
    loss='mse'
)

# Train autoencoder
history = autoencoder.fit(
    x_train,
    x_train,
    epochs=50,
    batch_size=32,
    shuffle=True,
    validation_split=0.1
)

# Reconstruct test data
x_pred = autoencoder.predict(
    x_test,
    verbose=0
)

# Calculate reconstruction error
reconstruction_error = np.mean(
    np.square(x_test - x_pred),
    axis=1
)

print("Reconstruction Errors:")
print(reconstruction_error[:10])

# Calculate training reconstruction error
train_pred = autoencoder.predict(
    x_train,
    verbose=0
)

train_error = np.mean(
    np.square(x_train - train_pred),
    axis=1
)

# Set threshold
threshold = np.percentile(
    train_error,
    95
)

print("Anomaly Threshold:", threshold)

# Detect anomalies
anomalies = reconstruction_error > threshold

# Display results
results = pd.DataFrame({
    'Actual_Customer_Index': x_test.shape[0] * [None],
    'Reconstruction_Error': reconstruction_error,
    'Anomaly': anomalies
})

